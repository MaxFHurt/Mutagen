"""Turn a supplied kit's LAYOUT.json into a module the app imports: ui/kits/<kit>/layout.js.

Data only; no image is changed. Each piece gets `liquid: true` when its supplied liquid mask has any coverage, so
solid steel pieces are shown as their assembled image and liquid-carrying ones get live liquid behind their overlay.
Run from the repo root after installing or replacing a kit:  python3 tools/kits/layout-module.py <kit> [...]
It also rewrites ui/kits/index.js, the list of installed kits the screens look up.
"""
import json
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

for kit in sys.argv[1:]:
    d = os.path.join(ROOT, 'ui/kits', kit)
    layout = json.load(open(os.path.join(d, 'LAYOUT.json')))
    for p in layout['pieces']:
        # Files that do not decode (truncated in delivery) are listed so the app can fall back instead of showing them.
        broken = []
        for key, f in (p.get('files') or {}).items():
            try:
                Image.open(os.path.join(d, f)).load()
            except Exception:
                broken.append(key)
        if broken:
            p['broken'] = broken
            print(f'  {kit}/{p["id"]}: broken {", ".join(broken)} - ask ChatGPT to re-send')
        mask = p.get('files', {}).get('mask')
        p['liquid'] = bool(mask) and bool((np.array(Image.open(os.path.join(d, mask)).convert('RGB'))[..., 0] > 127).any())
    with open(os.path.join(d, 'layout.js'), 'w') as f:
        f.write(f'// {kit}: generated from LAYOUT.json (supplied by ChatGPT) by tools/kits/layout-module.py. Do not edit.\n')
        f.write('export default ' + json.dumps(layout, indent=2) + ';\n')
    print(kit, sum(p['liquid'] for p in layout['pieces']), 'liquid pieces of', len(layout['pieces']))

# The index of installed kits (every ui/kits/<kit>/layout.js), so a screen uses its kit as soon as one is installed.
kits = sorted(k for k in os.listdir(os.path.join(ROOT, 'ui/kits')) if os.path.exists(os.path.join(ROOT, 'ui/kits', k, 'layout.js')))
with open(os.path.join(ROOT, 'ui/kits/index.js'), 'w') as f:
    f.write('// Installed screen kits, generated by tools/kits/layout-module.py. Do not edit.\n')
    for i, k in enumerate(kits):
        f.write(f"import k{i} from './{k}/layout.js';\n")
    f.write('export default {\n' + ''.join(f"  '{k}': k{i},\n" for i, k in enumerate(kits)) + '};\n')
skin = os.path.exists(os.path.join(ROOT, 'ui/kits/skin/SKIN.json'))
print('installed kits:', ', '.join(kits) or 'none', '| skin:', 'yes' if skin else 'no')

# The skin kit (ui/kits/skin/, see docs/KIT-CONTRACT.md): stretchable frames for the parts every other screen is built
# from. Writes ui/kits/skin.css (game side) and ui/kits/skin-deck.css (Deck Mutator) from SKIN.json; both are empty
# until a skin is installed, so nothing changes before then. Only the frames' sources and slices change, never a layout.
# part: (game-side selectors, Deck Mutator selectors, default border-image-width)
PARTS = {
    'button': ('.btn, .btn-frame', '.btn', '0.9rem 1.3rem'),
    'button-primary': ('.btn--confirm', '.btn.pri', '0.9rem 1.3rem'),
    'button-danger': ('.btn--cancel, .btn--danger', '.btn.danger', '0.9rem 1.3rem'),
    'square': ('.icon-btn, .tp__counter button, .tp__counters-add', 'button.pip', '0.6rem'),
    'panel': ('.frame, .panel, .tracker__head, .tp, .tlog, .setup-player, .game__left, .zone, .opps, .glog', '.panel', '1.85rem 3.85rem'),
    'modal': ('.modal__panel', '.modal > div, .modal .panel', '1.85rem 3.85rem'),
    'option': ('.option, .setup__tab', '', '0.8rem 1.2rem'),
    'option-on': ('.option.is-on, .setup__tab.is-on', '', '0.8rem 1.2rem'),
    'tab': ('', '.tab', '0.7rem 1rem 0 1rem'),
    'tab-on': ('', '.tab.on, .tab.active, .tab[aria-selected="true"]', '0.7rem 1rem 0 1rem'),
    'input': ('.input, .field input, .field select, .field textarea', 'input[type=text], input[type=search], select, textarea', '0.6rem 0.9rem'),
}
skin_dir = os.path.join(ROOT, 'ui/kits/skin')
css = {'skin.css': [], 'skin-deck.css': []}
if os.path.exists(os.path.join(skin_dir, 'SKIN.json')):
    spec = json.load(open(os.path.join(skin_dir, 'SKIN.json')))
    for part, (game_sel, deck_sel, width) in PARTS.items():
        if not os.path.exists(os.path.join(skin_dir, part + '.png')):
            continue
        p = spec.get('parts', {}).get(part, {})
        slice_ = ' '.join(str(v) for v in p.get('slice', [24, 24, 24, 24])) + (' fill' if p.get('fill', True) else '')
        w = p.get('width', width)
        for name, sel, prefix in (('skin.css', game_sel, 'skin/'), ('skin-deck.css', deck_sel, 'skin/')):   # relative to ui/kits/
            if sel:
                rule = (f"{sel} {{ border-style: solid; border-color: transparent; border-image: url('{prefix}{part}.png') {slice_} / {w} stretch;"
                        " background: none; box-shadow: none; filter: none; }")
                css[name].append(rule)
    if os.path.exists(os.path.join(skin_dir, 'back.png')):
        css['skin.css'].append(".btn-back img { content: url('skin/back.png'); }")
    for state in ('pressed', 'disabled'):
        if os.path.exists(os.path.join(skin_dir, f'button-{state}.png')):
            p = spec.get('parts', {}).get('button', {})
            slice_ = ' '.join(str(v) for v in p.get('slice', [24, 24, 24, 24])) + (' fill' if p.get('fill', True) else '')
            sel = {'pressed': (':active:not(:disabled)', ':active:not([disabled])'), 'disabled': (':disabled', '[disabled]')}[state]
            css['skin.css'].append(f".btn{sel[0]} {{ border-image-source: url('skin/button-{state}.png'); filter: none; }}")
            css['skin-deck.css'].append(f".btn{sel[1]} {{ border-image-source: url('skin/button-{state}.png'); opacity: 1; }}")
for name, rules in css.items():
    with open(os.path.join(ROOT, 'ui/kits', name), 'w') as f:
        f.write('/* MUTAGEN skin, generated from ui/kits/skin/SKIN.json by tools/kits/layout-module.py. Do not edit. */\n')
        f.write('\n'.join(rules) + ('\n' if rules else '/* No skin installed yet: nothing changes. */\n'))
print('skin rules:', len(css['skin.css']), 'game side,', len(css['skin-deck.css']), 'Deck Mutator')
